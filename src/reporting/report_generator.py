"""
Executive PDF and CSV analytical report generator for the Forest Fire Intelligence System.

Generates publication-quality PDF dossiers summarizing wildfire activity, spatial clusters,
and detected anomalies using ReportLab.
"""
from datetime import datetime
import html
import io
import logging
from typing import Dict, List, Optional, Any
import pandas as pd
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable,
)

logger = logging.getLogger(__name__)


class ReportGenerator:
    """Creates structured executive reports in PDF and CSV formats."""

    @staticmethod
    def _escape_text(text: str) -> str:
        """Escape XML/HTML characters to prevent ReportLab XML parser errors."""
        return html.escape(str(text))

    def generate_pdf_report(
        self,
        title: str,
        sections: List[Dict[str, Any]],
        output_path: Optional[str] = None,
    ) -> bytes:
        """
        Generate a professional analytical PDF report.

        Args:
            title: Title of the document.
            sections: List of section dicts:
                      [{'heading': str, 'text': str, 'table': pd.DataFrame or None}, ...]
            output_path: Optional filesystem path to write the PDF.

        Returns:
            PDF binary content as bytes.
        """
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=40,
            leftMargin=40,
            topMargin=40,
            bottomMargin=40,
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#1a252f"),
            spaceAfter=6,
        )
        subtitle_style = ParagraphStyle(
            "DocSubtitle",
            parent=styles["Normal"],
            fontName="Helvetica-Oblique",
            fontSize=11,
            leading=14,
            textColor=colors.HexColor("#7f8c8d"),
            spaceAfter=15,
        )
        heading_style = ParagraphStyle(
            "SectionHeading",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=14,
            leading=18,
            textColor=colors.HexColor("#c0392b"),
            spaceBefore=14,
            spaceAfter=6,
        )
        body_style = ParagraphStyle(
            "BodyDark",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=13.5,
            textColor=colors.HexColor("#2c3e50"),
            spaceAfter=8,
        )
        table_cell_style = ParagraphStyle(
            "TableCell",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=8,
            leading=10,
            textColor=colors.HexColor("#2c3e50"),
            alignment=1,  # Center
        )
        table_header_style = ParagraphStyle(
            "TableHeader",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=8.5,
            leading=11,
            textColor=colors.whitesmoke,
            alignment=1,
        )

        story = []

        # 1. Header Banner
        clean_title = self._escape_text(title)
        story.append(Paragraph(clean_title, title_style))
        now_str = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
        story.append(
            Paragraph(
                f"Generated by AI-Driven Forest Fire Intelligence System • {now_str}",
                subtitle_style,
            )
        )
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#c0392b"), spaceAfter=14))

        # 2. Add each section
        for section in sections:
            heading = section.get("heading", "")
            if heading:
                story.append(Paragraph(self._escape_text(heading), heading_style))

            text = section.get("text", "")
            if text:
                # Support multiple paragraphs split by double newline
                for para in text.split("\n\n"):
                    clean_para = self._escape_text(para.strip()).replace("\n", "<br/>")
                    if clean_para:
                        story.append(Paragraph(clean_para, body_style))

            tbl_df = section.get("table")
            if tbl_df is not None and isinstance(tbl_df, pd.DataFrame) and not tbl_df.empty:
                # Limit preview table to top 20 rows and 6 columns to fit page comfortably
                preview_df = tbl_df.iloc[:20, :6].copy()
                table_data = []

                # Headers
                headers = [
                    Paragraph(self._escape_text(str(c)), table_header_style)
                    for c in preview_df.columns
                ]
                table_data.append(headers)

                # Data rows
                for _, row in preview_df.iterrows():
                    table_data.append([
                        Paragraph(self._escape_text(str(val)), table_cell_style)
                        for val in row
                    ])

                t = Table(table_data, hAlign="LEFT")
                t.setStyle(TableStyle([
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#2c3e50")),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#bdc3c7")),
                    ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8f9fa")]),
                ]))
                story.append(Spacer(1, 4))
                story.append(t)
                story.append(Spacer(1, 10))

        # Build PDF
        try:
            doc.build(story)
            pdf_bytes = buffer.getvalue()
            buffer.close()

            if output_path:
                with open(output_path, "wb") as f:
                    f.write(pdf_bytes)
                logger.info(f"PDF report saved to disk: {output_path}")

            return pdf_bytes
        except Exception as exc:
            logger.error(f"Error compiling PDF report: {exc}")
            return b""

    def generate_summary_report(
        self,
        fire_df: pd.DataFrame,
        cluster_result: Optional[Dict[str, Any]] = None,
        anomaly_df: Optional[pd.DataFrame] = None,
    ) -> bytes:
        """
        Convenience builder for standard wildfire analytical briefing.

        Sections:
            1. Executive Overview & Data Provenance
            2. Detection Statistics & Regional Totals
            3. Spatial Hotspot Clustering
            4. Severe Outbreak & Outlier Anomalies

        Args:
            fire_df: Cleaned fire events.
            cluster_result: Spatial clustering dict.
            anomaly_df: Detected anomalies DataFrame.

        Returns:
            PDF report binary bytes.
        """
        n_events = len(fire_df) if fire_df is not None else 0
        mean_frp = (
            float(fire_df["fire_radiative_power"].mean())
            if fire_df is not None and "fire_radiative_power" in fire_df.columns and not fire_df.empty
            else 0.0
        )
        mean_b = (
            float(fire_df["brightness"].mean())
            if fire_df is not None and "brightness" in fire_df.columns and not fire_df.empty
            else 0.0
        )

        n_clusters = cluster_result.get("n_clusters", 0) if cluster_result else 0
        n_anomalies = (
            int(anomaly_df["is_anomaly_if"].sum())
            if anomaly_df is not None and "is_anomaly_if" in anomaly_df.columns
            else 0
        )

        overview_text = (
            f"This intelligence dossier provides situational awareness on {n_events} satellite "
            f"wildfire detections. The average brightness temperature across observed events is "
            f"{mean_b:.1f} K, with a mean Fire Radiative Power (FRP) of {mean_frp:.1f} MW.\n\n"
            "DISCLAIMER: Satellite detections represent radiative thermal signals captured during "
            "orbital passes and statistical estimations. Analytical findings are designed for "
            "environmental research and situational monitoring."
        )

        # Region stats table if country column exists
        stats_table = None
        if fire_df is not None and not fire_df.empty and "country" in fire_df.columns:
            stats_table = (
                fire_df.groupby("country")
                .agg(
                    Detections=("latitude", "count"),
                    Avg_Brightness=("brightness", "mean"),
                    Avg_FRP=("fire_radiative_power" if "fire_radiative_power" in fire_df.columns else "latitude", "mean"),
                )
                .round(1)
                .reset_index()
            )

        # Cluster text
        cluster_text = (
            f"Spatial density analysis grouped observations into {n_clusters} primary geographic "
            f"clusters based on coordinate proximity. Centroids represent aggregate thermal epicenters."
        )

        # Anomaly text
        anomaly_text = (
            f"Machine learning anomaly detection flagged {n_anomalies} high-intensity or geographically "
            f"isolated wildfire events requiring priority review."
        )

        sections = [
            {"heading": "1. Executive Overview", "text": overview_text, "table": None},
            {"heading": "2. Observation Statistics", "text": "Aggregated detection metrics by region:", "table": stats_table},
            {"heading": "3. Geographical Clustering", "text": cluster_text, "table": None},
            {"heading": "4. Thermal & Spatial Anomalies", "text": anomaly_text, "table": None},
        ]

        return self.generate_pdf_report("Wildfire Situation Assessment Report", sections)

    @staticmethod
    def dataframe_to_csv_bytes(df: pd.DataFrame) -> bytes:
        """
        Convert a DataFrame to UTF-8 encoded CSV bytes for download.

        Args:
            df: DataFrame to convert.

        Returns:
            CSV encoded as bytes.
        """
        if df is None or df.empty:
            return b""
        return df.to_csv(index=False).encode("utf-8")
